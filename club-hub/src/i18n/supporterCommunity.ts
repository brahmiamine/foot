export type SupporterCommunityAdminKey = keyof typeof copy.fr;

export function supporterCommunityAdminT(locale: Locale, key: SupporterCommunityAdminKey, values?: Record<string, string | number>): string {
  let text: string = copy[locale][key];
  if (!values) return text;
  for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

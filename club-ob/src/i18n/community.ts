export type CommunityTranslationKey = keyof typeof copy.fr;

export function communityT(locale: Locale, key: CommunityTranslationKey, values?: Record<string, string | number>): string {
  let text: string = copy[locale][key];
  if (!values) return text;
  for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
